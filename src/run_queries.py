"""Execute the documented SQL queries and render the audit trail.

Every query in `sql/03..07` carries a `-- name:` / `-- description:` header.
This module splits the files on those headers, runs each statement against the
SQLite warehouse built by `src/build_db.py`, and writes:

    reports/sql_results.md     - the full output of every query, in order
    reports/data_quality.md    - the data-quality section on its own
    reports/data_quality.json  - machine-readable check results

The markdown is the audit trail behind every number quoted in the README, the
Excel workbook, the Power BI model and the findings report.

Run after `build_db.py`:

    python src/run_queries.py
"""

from __future__ import annotations

import json
import re
import sqlite3
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

import config  # noqa: E402

HEADER_RE = re.compile(
    r"--\s*name:\s*(?P<name>[\w_]+)\s*\n--\s*description:\s*(?P<description>.+?)\n",
    re.MULTILINE,
)


def parse_queries(path: Path) -> list[tuple[str, str, str]]:
    """Split a query file into (name, description, sql) triples."""
    text = path.read_text(encoding="utf-8")
    matches = list(HEADER_RE.finditer(text))
    if not matches:
        raise ValueError(f"No '-- name:' headers found in {path.name}")
    queries: list[tuple[str, str, str]] = []
    for i, match in enumerate(matches):
        start = match.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        body = text[start:end].split("-- ====")[0]
        sql = body.strip().rstrip(";").strip()
        queries.append((match.group("name"), match.group("description").strip(), sql))
    return queries


def _markdown_table(df: pd.DataFrame, max_rows: int = 40) -> str:
    if df.empty:
        return "_(no rows)_\n"
    shown = df.head(max_rows)
    header = "| " + " | ".join(str(c) for c in shown.columns) + " |"
    rule = "|" + "|".join("---" for _ in shown.columns) + "|"
    lines = [header, rule]
    for _, row in shown.iterrows():
        cells = []
        for value in row:
            if value is None or (isinstance(value, float) and pd.isna(value)):
                cells.append("")
            elif isinstance(value, float):
                if value == int(value) and abs(value) < 1e15:
                    cells.append(f"{int(value):,}")
                else:
                    cells.append(f"{value:,.4f}".rstrip("0").rstrip("."))
            else:
                cells.append(str(value))
        lines.append("| " + " | ".join(cells) + " |")
    if len(df) > max_rows:
        lines.append(f"| _... {len(df) - max_rows:,} more rows (full result in the database)_ |" + " |" * (len(shown.columns) - 1))
    return "\n".join(lines) + "\n"


def main() -> None:
    conn = sqlite3.connect(config.DB_PATH)
    conn.row_factory = sqlite3.Row

    results: list[dict] = []
    dq_results: list[dict] = []

    for filename, section in config.SQL_SECTIONS:
        path = config.SQL_DIR / filename
        for name, description, sql in parse_queries(path):
            df = pd.read_sql_query(sql, conn)
            results.append(
                {
                    "section": section,
                    "file": filename,
                    "name": name,
                    "description": description,
                    "rows": len(df),
                    "frame": df,
                }
            )
            if filename == "03_data_quality.sql":
                dq_results.append(
                    {
                        "check": name,
                        "description": description,
                        "rows": len(df),
                        "result": df.to_dict(orient="records"),
                    }
                )
            print(f"[run_queries] {filename:38s} {name:38s} -> {len(df):>6,} rows")

    conn.close()

    # ------------------------------------------------------------ sql_results
    lines: list[str] = []
    lines.append("# SQL results")
    lines.append("")
    lines.append(
        "Generated by `src/run_queries.py`. Every query below is executed against the "
        "SQLite warehouse built by `src/build_db.py`. This file is the audit trail for "
        "the numbers quoted in the README, the Excel workbook and the Power BI model."
    )
    lines.append("")
    lines.append("| | |")
    lines.append("|---|---|")
    lines.append(f"| Database | `{config.DB_PATH.name}` |")
    lines.append("| Schema | `sql/01_schema.sql` |")
    lines.append("| Analytic layer | `sql/02_views.sql` |")
    lines.append(f"| Currency | {config.CURRENCY} (BRL) |")
    lines.append(f"| Reporting window | {config.CLEAN_WINDOW_LABEL} (clean) |")
    lines.append("")

    current_section = None
    for item in results:
        if item["section"] != current_section:
            current_section = item["section"]
            lines.append(f"\n## {current_section}\n")
            lines.append(f"Source: `{item['file']}`.\n")
        lines.append(f"\n### `{item['name']}`\n")
        lines.append(f"{item['description']}\n")
        lines.append("```")
        lines.append(_markdown_table(item["frame"]))
        lines.append("```")
        lines.append("")

    config.SQL_RESULTS_MD.parent.mkdir(parents=True, exist_ok=True)
    config.SQL_RESULTS_MD.write_text("\n".join(lines), encoding="utf-8")
    print(f"[run_queries] wrote {config.SQL_RESULTS_MD}")

    # ----------------------------------------------------------- data quality
    dq_lines = ["# Data quality report", ""]
    dq_lines.append(
        "Generated by `src/run_queries.py` from `sql/03_data_quality.sql`. "
        "Each check is a control that a finance or data team would run before "
        "trusting a number. Zero is the expected result for integrity checks; "
        "non-zero values are findings, explained in the comment column."
    )
    dq_lines.append("")
    dq_lines.append("## Summary of findings")
    dq_lines.append("")
    dq_lines.append("| # | Check | Result | What it means |")
    dq_lines.append("|---|---|---|---|")
    for i, item in enumerate(dq_results, start=1):
        dq_lines.append(f"| {i} | `{item['check']}` | {item['rows']:,} row(s) returned | {item['description']} |")
    dq_lines.append("")
    dq_lines.append("## Detail")
    for item in dq_results:
        dq_lines.append(f"\n### `{item['check']}`\n")
        dq_lines.append(f"{item['description']}\n")
        dq_lines.append("```")
        dq_lines.append(_markdown_table(pd.DataFrame(item["result"])))
        dq_lines.append("```")
        dq_lines.append("")
    config.DATA_QUALITY_MD.write_text("\n".join(dq_lines), encoding="utf-8")
    print(f"[run_queries] wrote {config.DATA_QUALITY_MD}")

    config.DATA_QUALITY_JSON.write_text(
        json.dumps(
            {
                "generated_by": "src/run_queries.py",
                "database": str(config.DB_PATH.name),
                "checks": [{k: v for k, v in item.items() if k != "frame"} for item in dq_results],
            },
            indent=2,
            default=str,
        ),
        encoding="utf-8",
    )
    print(f"[run_queries] wrote {config.DATA_QUALITY_JSON}")


if __name__ == "__main__":
    main()
